"""A graph-generator builder may place the nodes it generates.

A generated lattice or sheet has positions its builder computes, and every map drawn on it (a lattice field, a network panel) reads them from ``Node.position``. A builder returning a dict may supply ``node_positions``, one row of (x, y) or (x, y, z) per node in the network's distance unit.

These pin the contract: the positions reach ``Network.node_positions``, 2-D rows at z = 0; a declared node keeps its own; a wrong number of rows or columns is refused naming ``node_positions``; and the network companion a run freezes carries them.
"""

import numpy as np
import pytest
import yaml

from tvbo import Network, SimulationExperiment
from tvbo.data.dataref import network_companion_path
from tvbo.data.network_io import load_network

PLANAR = [[0.0, 0.0], [4.5, 0.0], [0.0, 7.25]]
SPATIAL = [[0.0, 0.0, 1.0], [4.5, 0.0, 2.0], [0.0, 7.25, 3.0]]
PLANAR_AT_Z0 = np.column_stack([PLANAR, np.zeros(len(PLANAR))])
OWN = {"x": -1.0, "y": -2.0, "z": -3.0}

_BUILDER_MODULE = f"""
import numpy as np

W = np.array([[0.0, 1.0, 0.5], [1.0, 0.0, 0.25], [0.5, 0.25, 0.0]])
PLANAR = np.array({PLANAR})
SPATIAL = np.array({SPATIAL})


def planar():
    return {{"weights": W, "node_positions": PLANAR}}


def spatial():
    return {{"weights": W, "node_positions": SPATIAL}}


def too_few_positions():
    return {{"weights": W, "node_positions": PLANAR[:2]}}


def four_columns():
    return {{"weights": W, "node_positions": np.column_stack([SPATIAL, SPATIAL[:, 0]])}}
"""


def _network_spec(builder: str, **declared) -> dict:
    """A three-node network generated by *builder* from the module beside its file, with the *declared* slots beside the generator."""
    generator = {"name": "Sheet", "type": "Sheet", "builder": {"name": builder, "module": "positioned_builders"}}
    return {"number_of_nodes": 3, "graph_generator": generator, **declared}


@pytest.fixture
def load(tmp_path):
    """Load a spec as *cls* from a file beside the builder module, as a study's recipe is loaded."""
    (tmp_path / "positioned_builders.py").write_text(_BUILDER_MODULE)

    def _load(spec: dict, cls=Network):
        path = tmp_path / "spec.yaml"
        path.write_text(yaml.safe_dump(spec))
        return cls.from_file(str(path))

    return _load


def test_planar_positions_land_on_the_generated_nodes_at_z_zero(load):
    net = load(_network_spec("planar"))
    np.testing.assert_array_equal(net.node_positions(), PLANAR_AT_Z0)
    assert net.get_centers() == {i: tuple(row) for i, row in enumerate(PLANAR_AT_Z0.tolist())}


def test_three_dimensional_positions_pass_through(load):
    np.testing.assert_array_equal(load(_network_spec("spatial")).node_positions(), SPATIAL)


@pytest.mark.parametrize(
    "nodes",
    [
        [{"id": 0, "label": "a", "position": OWN}, {"id": 1, "label": "b"}, {"id": 2, "label": "c"}],
        [{"label": "node_0", "position": OWN}],
    ],
    ids=["by-id", "by-label"],
)
def test_a_declared_nodes_own_position_is_kept(load, nodes):
    """The builder fills only the positions the declared nodes leave unset."""
    net = load(_network_spec("planar", nodes=nodes))
    np.testing.assert_array_equal(net.node_positions(), np.vstack([[OWN["x"], OWN["y"], OWN["z"]], PLANAR_AT_Z0[1:]]))


@pytest.mark.parametrize(
    ("builder", "message"),
    [
        ("too_few_positions", r"node_positions of shape \(2, 2\) for a 3-node weight matrix; one position per node"),
        ("four_columns", r"node_positions of shape \(3, 4\); each position is \(x, y\) or \(x, y, z\)"),
    ],
    ids=["rows", "columns"],
)
def test_positions_of_the_wrong_shape_are_refused_by_name(load, builder, message):
    with pytest.raises(ValueError, match=message):
        load(_network_spec(builder))


def test_the_network_companion_a_run_freezes_carries_the_positions(load, tmp_path):
    """Written as a result's provenance writes it (``freeze_yaml`` under ``get_network_stem``) and read as a reference to the run's network reads it (``network_companion_path``, ``load_network``)."""
    exp = load({"id": 1, "network": _network_spec("planar")}, SimulationExperiment)
    out = tmp_path / "derivatives"
    exp.freeze_yaml(out, network_stem=exp.get_network_stem())
    frozen = load_network(network_companion_path(out / f"{exp.get_result_stem()}.h5"))
    np.testing.assert_array_equal(frozen.node_positions(), PLANAR_AT_Z0)
